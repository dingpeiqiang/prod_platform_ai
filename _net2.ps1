$g = [System.Text.Encoding]::GetEncoding(936)
$tests = @(
  ,@(0xef,0xbc,0x9a,0x0d)
  ,@(0xef,0xbc,0x9a,0x0a)
  ,@(0xef,0xbc,0x9a,0x41)
  ,@(0xe5,0x85,0x83,0x4d)
  ,@(0xe5,0x85,0x83,0x27)
  ,@(0xe5,0x85,0x83,0x20)
)
foreach ($b in $tests) {
  $s = $g.GetString([byte[]]$b)
  $hex = ($s.ToCharArray() | ForEach-Object { ([int]$_).ToString('x4') }) -join ' '
  Write-Output ("IN=" + (($b | ForEach-Object { $_.ToString('x2') }) -join ' ') + " OUT=" + $hex)
}
