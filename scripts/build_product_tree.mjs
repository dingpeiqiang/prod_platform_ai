function walk(node, levels) {
  const depth = levels.length + 1;
  const lv = ['', '', '', '', '', ''];
  for (let i = 0; i < 3; i += 1) lv[i] = levels[i] ?? '';
  if (depth <= 6) lv[depth - 1] = node.name;
  rows.push({ lv, name: node.name, desc: node.desc, depth });
  const next = [...levels, node.name];
  node.children.forEach((c) => walk(c, next));
}
