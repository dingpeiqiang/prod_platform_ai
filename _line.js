const fs = require('fs');
const { gbkEncode, reconstruct } = require('./_recover.js');
const f = process.argv[2];
const ln = parseInt(process.argv[3], 10);
const bak = fs.readFileSync(f, 'utf8');
const line = bak.split('\n')[ln - 1];
console.log('BAKSTR', JSON.stringify(line));
const B = gbkEncode(line);
console.log('GBKBYTES', [...B].map(b => b.toString(16)).join(' '));
const { bytes, plan } = reconstruct(B);
console.log('PLAN', plan.map(p => `pos=${p.pos} head=${p.head.map(b => b.toString(16))} need=${p.need}`).join(' | '));
const { recover } = require('./_recover.js');
console.log('RECON', JSON.stringify(recover(f).split('\n')[ln - 1]));
